#!/usr/bin/env node
// Write spacegroupdata.js, the space group generators from data/SpaceGroupData.txt for the
// browser (AMC -> CIF builds each group's symmetry operators from them with symmetry.js).
// The same file goes to the repo root and the WordPress plugin's assets.
//
// Usage: node scripts/build_spacegroup_data.js
//
// Rerun after editing SpaceGroupData.txt. Check the .txt first with space_group_csv.js, which
// reports bad lines; this script only copies the generators across.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const INPUT = path.join(ROOT, 'data', 'SpaceGroupData.txt');
const OUTPUTS = ['spacegroupdata.js', 'wordpress-plugin/odr-rruff-cifviewer/assets/spacegroupdata.js'];

const entries = [];
for (const line of fs.readFileSync(INPUT, 'utf8').split(/\r?\n/)) {
  if (!line.trim() || /^(Date|Note):/.test(line)) continue;
  const symbol = line.trim().split(/\s+/)[0];
  const gens = [...line.matchAll(/(\d+)\s+'([^']*)'/g)].map(([, order, op]) => [Number(order), op]);
  entries.push(`  ${JSON.stringify(symbol)}: ${JSON.stringify(gens)},`);
}

const out = `// Generated by scripts/build_spacegroup_data.js from data/SpaceGroupData.txt - edit the .txt
// and rerun that script instead of editing this file.
// Each space group symbol (as in the .txt, e.g. "P2_1/c:2" or "*P4/ncc[.25,-.25,0]") maps to
// its generators as [order, operator] pairs.
const SPACE_GROUP_GENERATORS = {
${entries.join('\n')}
};
`;

for (const file of OUTPUTS) fs.writeFileSync(path.join(ROOT, file), out);
console.log(`${entries.length} space groups written to:\n  ${OUTPUTS.join('\n  ')}`);
